def cols(rows):
    out = []
    for x in range(8):
        b = 0
        for y in range(8):
            if rows[y][x] == '#':
                b |= 1 << y
        out.append(b)
    return out


def emit(f):
    w = f.write
    w("// =================================================================================="
      "=\n")
    w("// Tiny RPG tileset and sprites (generated by tools/gentiles.py)\n")
    w("// ===================================================================================\n")
    w("// One byte per pixel column, bit0 = top row, matching SSD1306 horizontal addressing.\n")
    w("// Do not edit by hand: change the ASCII art in tools/gentiles.py and re-run it.\n")
    w("\n#pragma once\n#include <stdint.h>\n\n")

    solid = [n for n, _ in TILES].index("TREE")   # first blocking tile, never hard code it
    w("// Tile index -> picture. 0..%d are walkable, TW_SOLID upwards blocks.\n" % (solid - 1))
    w("// Each biome keeps three ground pictures so a field is never visibly tiled.\n")
    for i, (name, _) in enumerate(TILES):
        w("#define TW_%-10s %2d\n" % (name, i))
    w("#define TW_%-10s %2d\n" % ("SOLID", solid))
    w("#define TW_%-10s %2d\n" % ("COUNT", len(TILES)))
    w("\nconst uint8_t world_tiles[%d * 8] = {\n" % len(TILES))
    for name, rows in TILES:
        w("  " + ", ".join("0x%02X" % b for b in cols(rows)) + ",   // %s\n" % name)
    w("};\n\n")

    w("// Hero: DOWN, UP, LEFT, RIGHT, two frames each\n")
    w("const uint8_t hero_spr[%d * 8] = {\n" % len(SPRITES))
    for name, rows in SPRITES:
        w("  " + ", ".join("0x%02X" % b for b in cols(rows)) + ",   // %s\n" % name)
    w("};\n\n")

    w("// Monsters: rabbit, poring, bird, two frames each\n")
    w("#define MON_FRAMES 2\n")
    w("const uint8_t mon_spr[%d * 8] = {\n" % len(MON))
    for name, rows in MON:
        w("  " + ", ".join("0x%02X" % b for b in cols(rows)) + ",   // %s\n" % name)
    w("};\n\n")

    w("// Bosses, 16x16, one frame each: Malenia, sand lord, frost king\n")
    w("#define BOSS_W 16\n#define BOSS_PAGES 2\n")
    w("const uint8_t boss_spr[%d * BOSS_W * BOSS_PAGES] = {\n" % len(BOSS))
    for name, rows in BOSS:
        c = cols_of16(rows)
        w("  " + ", ".join("0x%02X" % b for b in c) + ",   // %s\n" % name)
    w("};\n\n")

    w("// Attack effects: four slashes, then the mage bolt which needs no direction\n")
    w("#define FX_SLASH 0\n#define FX_FIRE 4\n#define FX_BOLT 5\n")
    w("const uint8_t fx_spr[%d * 8] = {\n" % len(FX))
    for name, rows in FX:
        w("  " + ", ".join("0x%02X" % b for b in cols(rows)) + ",   // %s\n" % name)
    w("};\n")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "src/worldtiles.h"
    with open(out, "w") as f:
        emit(f)
    print("wrote %s: %d tiles, %d sprite frames" % (out, len(TILES), len(SPRITES)))
