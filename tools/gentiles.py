def cols_of16(rows):
    """16 wide by 16 tall, emitted as two pages of 16 columns."""
    out = []
    for page in range(2):
        for x in range(16):
            b = 0
            for bit in range(8):
                if rows[page * 8 + bit][x] == '#':
                    b |= 1 << bit
            out.append(b)
    return out


