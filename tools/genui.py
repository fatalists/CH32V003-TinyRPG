# ===================================================================================
# Banner composition: a keep with two towers, then the title beneath it
# ===================================================================================
BANNER_W, BANNER_H = 128, 40


def blank(w, h):
    return [[0] * w for _ in range(h)]


def rect(img, x0, y0, x1, y1, fill=True):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if 0 <= x < len(img[0]) and 0 <= y < len(img):
                if fill or y in (y0, y1) or x in (x0, x1):
                    img[y][x] = 1


def battlements(img, x0, x1, y, step=4, depth=3):
    """Crenellations: notch out every other block of the top edge."""
    x = x0
    while x <= x1:
        for xx in range(x, min(x + step // 2, x1 + 1)):
            for yy in range(y, y + depth):
                if 0 <= yy < len(img):
                    img[yy][xx] = 0
        x += step


def window(img, x, y, w=2, h=3):
    """Punch a dark opening, which keeps a solid silhouette from reading as a slab."""
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            if 0 <= xx < len(img[0]) and 0 <= yy < len(img):
                img[yy][xx] = 0


def tower(img, x0, x1, ytop, ybase):
    rect(img, x0, ytop, x1, ybase)
    battlements(img, x0, x1, ytop)
    mid = (x0 + x1) // 2
    window(img, mid - 1, ytop + 5)
    window(img, mid - 1, ytop + 10)


def pennant(img, x, ytop):
    for y in range(ytop - 6, ytop + 1):
        if 0 <= y < len(img):
            img[y][x] = 1
    for dy in range(3):
        for dx in range(1, 6 - dy):
            yy = ytop - 5 + dy
            if 0 <= yy < len(img) and x + dx < len(img[0]):
                img[yy][x + dx] = 1


def build_banner():
    """Just the name in big letters between two rules. A castle silhouette cost 239
    bytes even compressed, and the flash was needed for dungeons and bosses."""
    img = blank(BANNER_W, BANNER_H)
    for x in range(4, BANNER_W - 4):
        img[2][x] = 1
        img[3][x] = 1
        img[36][x] = 1
        img[37][x] = 1
    for ci, ch in enumerate(TITLE):
        art = BIG[ch]
        for y in range(8):
            for x in range(8):
                if art[y][x] == '#':
                    for dy in range(2):
                        for dx in range(2):
                            px = ci * 16 + x * 2 + dx
                            py = 11 + y * 2 + dy
                            if 0 <= px < BANNER_W and 0 <= py < BANNER_H:
                                img[py][px] = 1
    return img


