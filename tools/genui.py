def cols_of(rows, w, h):
    """Pack rows of characters or ints into page-major column bytes."""
    out = []
    for page in range(h // 8):
        for x in range(w):
            b = 0
            for bit in range(8):
                cell = rows[page * 8 + bit][x]
                on = (cell == '#') if isinstance(cell, str) else bool(cell)
                if on:
                    b |= 1 << bit
            out.append(b)
    return out


def glyph_cols(art4):
    rows = list(art4) + ["...."]
    out = []
    for x in range(4):
        b = 0
        for y in range(8):
            if rows[y][x] == '#':
                b |= 1 << y
        out.append(b)
    return out


def packbits(d):
    """Same PackBits the map uses, so the decoder shape is familiar."""
    out = bytearray()
    i, n = 0, len(d)
    while i < n:
        run = 1
        while i + run < n and d[i + run] == d[i] and run < 127:
            run += 1
        if run >= 3:
            out.append(0x80 | run); out.append(d[i]); i += run
        else:
            lit = bytearray()
            while i < n and len(lit) < 127:
                r2 = 1
                while i + r2 < n and d[i + r2] == d[i] and r2 < 4:
                    r2 += 1
                if r2 >= 3:
                    break
                lit.append(d[i]); i += 1
            out.append(len(lit)); out += lit
    return bytes(out)


def emit(f):
    w = f.write
    w("// ===================================================================================\n")
    w("// Tiny RPG interface art (generated by tools/genui.py)\n")
    w("// ===================================================================================\n")
    w("// One byte per pixel column, bit0 = top row of the page.\n")
    w("// Do not edit by hand: change the art in tools/genui.py and re-run it.\n")
    w("\n#pragma once\n#include <stdint.h>\n\n")

    w("// --- 4x8 font, 5 pixel advance -------------------------------------------------\n")
    w("#define FONT_ADV 5\n")
    w("#define FONT_N   %d\n" % len(FONT_ORDER))
    w("const uint8_t ui_font[FONT_N * 4] = {\n")
    for ch in FONT_ORDER:
        cols = glyph_cols(FONT[ch])
        label = "space" if ch == ' ' else ch
        w("  " + ", ".join("0x%02X" % b for b in cols) + ",   // %s\n" % label)
    w("};\n\n")

    banner = build_banner()
    bc = cols_of(banner, BANNER_W, BANNER_H)

    hc = (cols_of(HERO_WARRIOR, 16, 24) + cols_of(HERO_MAGE, 16, 24)
          + cols_of(HERO_SHOP, 16, 24))
    w("// --- figures, warrior, mage then the trader, 16x24 ----------------------------------\n")
    w("#define HERO_W 16\n#define HERO_PAGES 3\n")
    w("#define HERO_BYTES (HERO_W * HERO_PAGES)\n")
    w("#define HERO_SHOP 2                     // the trader, drawn like a class figure\n")
    w("const uint8_t ui_hero[3 * HERO_BYTES] = {   // warrior, mage, trader\n")
    for i in range(0, len(hc), 16):
        w("  " + ", ".join("0x%02X" % b for b in hc[i:i + 16]) + ",\n")
    w("};\n\n")

    w("// --- item icons, %dx12 ---------------------------------------------------------\n"
      % ICON_W)
    w("#define ICON_W     %d\n#define ICON_PAGES 2\n#define ICON_BYTES %d\n"
      % (ICON_W, ICON_W * 12 // 8))
    for i, name in enumerate(ICON_ORDER):
        w("#define ICON_%-7s %d\n" % (name, i))
    w("const uint8_t ui_icons[%d * ICON_BYTES] = {\n" % len(ICON_ORDER))
    # An icon is 12x12, which is 144 bits exactly. Storing it as two 8-row pages would
    # waste four blank rows per column, so the columns are packed twelve bits each.
    for name in ICON_ORDER:
        art = list(ICONS[name]) + [_B] * (12 - len(ICONS[name]))
        bits = bytearray(ICON_W * 12 // 8)
        for c in range(ICON_W):
            for r in range(12):
                if art[r][c] not in ". ":
                    k = c * 12 + r
                    bits[k >> 3] |= 1 << (k & 7)
        w("  " + ", ".join("0x%02X" % b for b in bits) + ",   // %s\n" % name)
    w("};\n")


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "src/ui_art.h"
    with open(out, "w") as f:
        emit(f)
    print("wrote %s: %d glyphs, banner %dx%d, %d icons"
          % (out, len(FONT_ORDER), BANNER_W, BANNER_H, len(ICON_ORDER)))
